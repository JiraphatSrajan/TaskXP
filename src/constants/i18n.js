const getByPath = (obj, path) => path.split('.').reduce((acc, part) => (acc && acc[part] !== undefined ? acc[part] : undefined), obj);

export const translate = (language = 'English', key, vars = {}) => {
  const scoped = dictionary[language] || dictionary.English;
  const fallback = dictionary.English;
  const value = getByPath(scoped, key) ?? getByPath(fallback, key) ?? key;

  if (typeof value !== 'string') {
    return value;
  }

  return Object.keys(vars).reduce((text, name) => text.replace(new RegExp(`{{${name}}}`, 'g'), String(vars[name])), value);
};

